#!/usr/bin/env node
// Build the line -> heading id map of the frozen English source.
//
// The Korean article keeps a strict line-to-line correspondence with
// docs/original/article.en.mdx (see TRANSLATION_GUIDE.md). The remark plugin
// plugins/remark/source-heading-ids.mjs uses this map so every heading keeps
// its English id after translation, and internal links such as
// (#the-training-marathon) keep working whichever week translates first.
//
// The Space build only copies app/, so the map is committed as a module.
// Run again only if the frozen English source changes:
//   cd app && node scripts/generate-source-heading-ids.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import GithubSlugger from 'github-slugger';

const sourcePath = fileURLToPath(new URL('../../docs/original/article.en.mdx', import.meta.url));
const outputPath = fileURLToPath(new URL('../plugins/remark/source-heading-ids.data.mjs', import.meta.url));

const lines = readFileSync(sourcePath, 'utf8').split(/\r?\n/);
const slugger = new GithubSlugger();
const entries = [];

let start = 0;
if (lines[0]?.trim() === '---') {
  start = lines.findIndex((line, index) => index > 0 && line.trim() === '---') + 1;
}

let fence = null;
for (let index = start; index < lines.length; index += 1) {
  const stripped = lines[index].trim();
  if (fence) {
    if (new RegExp(`^\\${fence.char}{${fence.size},}\\s*$`).test(stripped)) fence = null;
    continue;
  }
  const fenceMatch = stripped.match(/^(`{3,}|~{3,})/);
  if (fenceMatch) {
    fence = { char: fenceMatch[1][0], size: fenceMatch[1].length };
    continue;
  }
  const heading = lines[index].match(/^#{1,6}\s+(.*?)\s*$/);
  if (!heading) continue;
  // Plain text of the heading, as rehype-slug sees it.
  const text = heading[1]
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]*>/g, '')
    .replace(/\*\*|__|`/g, '')
    .replace(/(^|\s)[*_]|[*_](?=\s|$)/g, '$1')
    .trim();
  entries.push({ line: index + 1, id: slugger.slug(text), text });
}

const body = entries
  .map(({ line, id, text }) => `  ${line}: ${JSON.stringify(id)}, // ${text.replace(/\s+/g, ' ')}`)
  .join('\n');

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-source-heading-ids.mjs from docs/original/article.en.mdx. Do not edit by hand.\n` +
    `// Source line number -> heading id of the English original.\n` +
    `export const SOURCE_HEADING_IDS = {\n${body}\n};\n`,
);
console.log(`Wrote ${entries.length} heading ids to ${outputPath}`);
